function normalizeLang(l) {
  const code = String(l || '').toLowerCase().split(/[-_]/)[0];
  return UI_LANGUAGES.includes(code) ? code : null;
}

function hasMessage(lang, key) {
  return key in (MESSAGES[lang] || {}) || key in MESSAGES.en;
}

/** Translate key in lang with {placeholders}; plural messages use params.n. */
function translate(lang, key, params = {}) {
  let msg = MESSAGES[lang]?.[key] ?? MESSAGES.en[key] ?? key;
  if (typeof msg === 'object') {
    const cat = new Intl.PluralRules(DATE_LOCALES[lang] || lang).select(params.n ?? 0);
    msg = msg[cat] ?? msg.other ?? msg.many ?? '';
  }
  return msg.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}
